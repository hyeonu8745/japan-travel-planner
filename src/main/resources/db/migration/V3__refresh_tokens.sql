-- V3: 갱신 토큰 (11-15 보안). 원문은 저장하지 않고 SHA-256 해시만. family_id = 로그인한 브라우저 하나
CREATE TABLE public.refresh_tokens (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    token_hash character varying(64) NOT NULL UNIQUE,
    family_id character varying(36) NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    expires_at timestamp(6) with time zone NOT NULL,
    revoked_at timestamp(6) with time zone,
    revoke_reason character varying(20)
);

CREATE INDEX idx_refresh_tokens_user ON public.refresh_tokens (user_id, expires_at);
CREATE INDEX idx_refresh_tokens_family ON public.refresh_tokens (family_id);
